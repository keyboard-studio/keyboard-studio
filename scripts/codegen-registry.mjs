#!/usr/bin/env node
/**
 * Derives the IANA registered-variant and registered-language tables from the
 * pinned `language-subtag-registry` npm package.
 *
 * Input:  node_modules/language-subtag-registry/data/json/{variant,language,registry,meta}.json
 * Output: packages/engine/src/langtags/generated/variants.ts
 *         packages/engine/src/langtags/generated/registeredLanguages.ts
 *
 * Both outputs are sorted by subtag (code-unit order) and carry a header naming
 * the package version and the registry File-Date.  Deterministic: identical
 * input -> byte-identical output.  Never hand-edit the outputs.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const PKG_DIR = join(ROOT, 'node_modules', 'language-subtag-registry');
const JSON_DIR = join(PKG_DIR, 'data', 'json');
const OUT_DIR = join(ROOT, 'packages', 'engine', 'src', 'langtags', 'generated');

if (!existsSync(join(JSON_DIR, 'registry.json'))) {
  console.error('[ERROR] language-subtag-registry data not found at:');
  console.error(`        ${JSON_DIR}`);
  console.error('        Run: pnpm install');
  process.exit(1);
}

const readJson = (name) => JSON.parse(readFileSync(join(JSON_DIR, name), 'utf8'));
const version = JSON.parse(readFileSync(join(PKG_DIR, 'package.json'), 'utf8')).version;
const fileDate = readJson('meta.json')['File-Date'];
const registry = readJson('registry.json');

// variant.json / language.json map subtag -> index into registry.json.
const rowsOf = (name) =>
  Object.entries(readJson(name))
    .map(([subtag, i]) => {
      const row = registry[i];
      if (!row || row.Subtag !== subtag) {
        console.error(`[ERROR] ${name}: index for "${subtag}" does not resolve to its registry row`);
        process.exit(1);
      }
      return row;
    })
    .sort((a, b) => (a.Subtag < b.Subtag ? -1 : a.Subtag > b.Subtag ? 1 : 0));

const header = (what) =>
  `// GENERATED by scripts/codegen-registry.mjs -- do not edit.\n` +
  `// ${what}\n` +
  `// Source: language-subtag-registry@${version}, File-Date ${fileDate}\n`;

const q = (s) => JSON.stringify(s);

// ---------------------------------------------------------------- variants ---
const variants = rowsOf('variant.json');
let vOut = header('IANA registered BCP 47 variant subtags.');
vOut += `\nexport interface RegisteredVariant {\n  readonly subtag: string;\n  readonly descriptions: readonly string[];\n  readonly prefixes: readonly string[];\n  readonly deprecated: boolean;\n}\n\n`;
vOut += `export const registeredVariants: readonly RegisteredVariant[] = [\n`;
for (const r of variants) {
  vOut +=
    `  { subtag: ${q(r.Subtag)}, descriptions: ${JSON.stringify(r.Description ?? [])}, ` +
    `prefixes: ${JSON.stringify(r.Prefix ?? [])}, deprecated: ${r.Deprecated ? 'true' : 'false'} },\n`;
}
vOut += `];\n`;

// --------------------------------------------------------------- languages ---
const languages = rowsOf('language.json');
let lOut = header('IANA registered BCP 47 language subtags (includes the qaa..qtz private-use range).');
lOut += `\nexport interface RegisteredLanguage {\n  readonly subtag: string;\n  readonly description: string;\n  readonly scope?: string;\n  readonly macrolanguage?: string;\n}\n\n`;
lOut += `export const registeredLanguages: readonly RegisteredLanguage[] = [\n`;
for (const r of languages) {
  let line = `  { subtag: ${q(r.Subtag)}, description: ${q((r.Description ?? [])[0] ?? '')}`;
  if (r.Scope) line += `, scope: ${q(r.Scope)}`;
  if (r.Macrolanguage) line += `, macrolanguage: ${q(r.Macrolanguage)}`;
  lOut += `${line} },\n`;
}
lOut += `];\n`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'variants.ts'), vOut);
writeFileSync(join(OUT_DIR, 'registeredLanguages.ts'), lOut);
console.log(`[OK] codegen-registry: ${variants.length} variants, ${languages.length} languages (File-Date ${fileDate})`);
