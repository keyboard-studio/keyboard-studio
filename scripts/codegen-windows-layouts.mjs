#!/usr/bin/env node
/**
 * Derives the Windows-layout catalog behind the studio's community-layout
 * picker (spec 076 FR-023, amendment A4) from the Keyman "basic" keyboards in
 * the sibling keyboards corpus (`release/basic/basic_kbd*`), each of which
 * mirrors one Windows layout.
 *
 * Per keyboard: id, display name, BCP47 languages (id + name), a coarse family
 * (qwerty | qwertz | azerty | non-roman | other) derived from the base-layer
 * outputs of K_Q, K_W, K_Y, K_Z, K_A, and the reference host id when the
 * keyboard IS one of the five reference hosts.
 *
 * Also refreshes the delimited generated section of docs/keyboard-index.md
 * (the keyboard phonebook) so every catalog keyboard has a row.
 *
 * Usage:
 *   node scripts/codegen-windows-layouts.mjs [--keyboards <path-to-keyboards-checkout>]
 *
 * The output is COMMITTED (CI has no corpus) and this script is NOT in the
 * prebuild chain. Re-run after a corpus bump.
 *
 * Output:
 *   packages/studio/src/lib/generated/windowsLayouts.generated.json
 *   docs/keyboard-index.md (between the WINDOWS-LAYOUTS markers)
 */

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { HOST_KEYBOARDS } from "./codegen-host-layouts.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");

export const OUTPUT_PATH = join(
  REPO_ROOT, "packages", "studio", "src", "lib", "generated", "windowsLayouts.generated.json",
);
export const INDEX_PATH = join(REPO_ROOT, "docs", "keyboard-index.md");
export const BEGIN_MARK = "<!-- BEGIN WINDOWS-LAYOUTS (generated by scripts/codegen-windows-layouts.mjs; do not edit) -->";
export const END_MARK = "<!-- END WINDOWS-LAYOUTS -->";

const KEYBOARD_FOR_HOST = Object.fromEntries(Object.entries(HOST_KEYBOARDS).map(([h, k]) => [k, h]));

function decodeXml(s) {
  return s
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'").replace(/&amp;/g, "&").trim();
}

/** Name, author/copyright and languages from a .kps (mirrors engine kps-parser fields). */
export function parseKps(text) {
  const info = /<Info>([\s\S]*?)<\/Info>/.exec(text)?.[1] ?? "";
  const name = decodeXml(/<Name[^>]*>([^<]*)<\/Name>/.exec(info)?.[1] ?? "");
  const author = decodeXml(/<Author[^>]*>([^<]*)<\/Author>/.exec(info)?.[1] ?? "");
  const copyright = decodeXml(/<Copyright[^>]*>([^<]*)<\/Copyright>/.exec(info)?.[1] ?? "");
  const languages = [];
  for (const m of text.matchAll(/<Language\s+ID="([^"]+)"[^>]*>([^<]*)<\/Language>/g)) {
    languages.push({ id: decodeXml(m[1]), name: decodeXml(m[2]) });
  }
  return { name, author: author || copyright, languages };
}

function firstOutputChar(raw) {
  const out = raw.trim();
  const u = /^U\+([0-9a-f]{4,6})/i.exec(out);
  if (u) return String.fromCodePoint(parseInt(u[1], 16));
  const q = /^(?:'([^']+)'|"([^"]+)")/.exec(out);
  if (q) return q[1] ?? q[2];
  return undefined;
}

/** Base-layer (no Shift/AltGr) output of the given key ids; caps-state NCAPS/CAPS rules count. */
export function baseOutputs(kmnText, keys) {
  const wanted = new Set(keys);
  const res = {};
  for (const line of kmnText.split(/\r?\n/)) {
    const m = /^\s*\+\s*\[([^\]]*)\]\s*>\s*(.*?)\s*$/.exec(line);
    if (!m) continue;
    const toks = m[1].trim().split(/\s+/);
    const key = toks.pop();
    if (key === undefined || !wanted.has(key.toUpperCase())) continue;
    if (toks.some((t) => !/^N?CAPS$/i.test(t))) continue;
    const id = key.toUpperCase();
    if (id in res) continue;
    const ch = firstOutputChar(m[2]);
    if (ch !== undefined) res[id] = ch;
  }
  return res;
}

const isLatin = (c) => /^\p{Script=Latin}$/u.test(c);

/** Coarse family from base outputs of K_Q K_W K_Y K_Z K_A. */
export function deriveFamily(o) {
  const keys = ["K_Q", "K_W", "K_Y", "K_Z", "K_A"];
  const present = keys.map((k) => o[k]).filter((v) => v !== undefined);
  if (present.length > 0 && present.some((v) => !isLatin(v))) return "non-roman";
  if (present.length < keys.length) return "other";
  const l = (k) => o[k].toLowerCase();
  if (l("K_Q") === "a" && l("K_A") === "q") return "azerty";
  if (l("K_Y") === "z" && l("K_Z") === "y") return "qwertz";
  if (l("K_Q") === "q" && l("K_W") === "w" && l("K_Y") === "y") return "qwerty";
  return "other";
}

export function buildCatalog(keyboardsDir) {
  const basic = join(keyboardsDir, "release", "basic");
  const ids = readdirSync(basic).filter((d) => /^basic_kbd/.test(d)).sort();
  const layouts = [];
  const authors = {};
  for (const id of ids) {
    const kps = join(basic, id, "source", `${id}.kps`);
    const kmn = join(basic, id, "source", `${id}.kmn`);
    if (!existsSync(kps) || !existsSync(kmn)) continue;
    const info = parseKps(readFileSync(kps, "utf8"));
    const family = deriveFamily(baseOutputs(readFileSync(kmn, "utf8"), ["K_Q", "K_W", "K_Y", "K_Z", "K_A"]));
    const entry = {
      id,
      name: info.name.replace(/\s+Basic$/i, "") || id,
      languages: info.languages,
      family,
    };
    if (KEYBOARD_FOR_HOST[id] !== undefined) entry.host = KEYBOARD_FOR_HOST[id];
    layouts.push(entry);
    authors[id] = info.author;
  }
  for (const [host, kb] of Object.entries(HOST_KEYBOARDS)) {
    if (!layouts.some((l) => l.id === kb)) throw new Error(`reference host ${host}: keyboard ${kb} missing from corpus`);
  }
  return { layouts, authors };
}

function corpusCommit(dir) {
  try {
    return execFileSync("git", ["-C", dir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

function tick(s) { return `\`${s}\``; }

export function indexSection(layouts, authors) {
  const rows = layouts.map((l) => {
    const tags = l.languages.map((x) => x.id);
    const shown = tags.slice(0, 15).map(tick).join(", ");
    const langs = tags.length > 15 ? `${shown} … (+${tags.length - 15} more)` : shown;
    return `| ${l.name} Basic | ${tick(l.id)} | ${langs} | ${authors[l.id] ?? ""} | ${tick(`../keyboards/release/basic/${l.id}`)} |`;
  });
  return [
    BEGIN_MARK,
    "",
    "### Windows-layout Basic keyboards",
    "",
    "Every `basic_kbd*` keyboard (the Windows-layout catalog behind the community-layout picker). Regenerate with `node scripts/codegen-windows-layouts.mjs`.",
    "",
    "| Keyboard | id | Languages (BCP47) | Author | Path |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
    END_MARK,
  ].join("\n");
}

/** Drop hand-written basic_kbd rows (superseded by the generated section) and splice the section in. */
export function spliceIndex(md, section) {
  const b = md.indexOf(BEGIN_MARK);
  if (b !== -1) {
    const e = md.indexOf(END_MARK, b);
    if (e === -1) throw new Error("keyboard-index.md: BEGIN marker without END marker");
    return md.slice(0, b) + section + md.slice(e + END_MARK.length);
  }
  const kept = md.split("\n").filter((ln) => !/^\|[^|]*\| `basic_kbd/.test(ln)).join("\n");
  return `${kept.replace(/\s*$/, "")}\n\n${section}\n`;
}

function main(argv) {
  const flag = argv.indexOf("--keyboards");
  const dir = resolve(flag !== -1 ? argv[flag + 1] : join(REPO_ROOT, "..", "keyboards"));
  const { layouts, authors } = buildCatalog(dir);
  const doc = {
    $comment:
      "GENERATED by scripts/codegen-windows-layouts.mjs from release/basic/basic_kbd* in the keyboards corpus. Do not edit; regenerate with: node scripts/codegen-windows-layouts.mjs",
    generated: new Date().toISOString().slice(0, 10),
    source: { repo: "keyboard-studio/keyboards", commit: corpusCommit(dir) },
    layouts,
  };
  writeFileSync(OUTPUT_PATH, `${JSON.stringify(doc, null, 1)}\n`);
  writeFileSync(INDEX_PATH, spliceIndex(readFileSync(INDEX_PATH, "utf8"), indexSection(layouts, authors)));
  const fam = {};
  for (const l of layouts) fam[l.family] = (fam[l.family] ?? 0) + 1;
  console.log(`[OK] codegen-windows-layouts: ${layouts.length} layouts ${JSON.stringify(fam)} -> ${OUTPUT_PATH}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
