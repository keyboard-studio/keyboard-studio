// ---------------------------------------------------------------------------
// HISTORY.md parsing (3.3, 3.4, 3.5, 3.6/7.1, 3.7)
// ---------------------------------------------------------------------------

/**
 * One parsed HISTORY.md entry. Entries are ATX headings (`## <version>
 * (<date>)`) as generated by the scaffolder / adapt-staging (spec 059/064) —
 * NOT the setext/hyphen-underline style the criteria prose describes, which
 * predates the tool's own generator. `version`/`date` are `null` when the
 * heading text doesn't match the `<version> (<date>)` shape at all.
 */
export interface HistoryEntry {
  /** Heading text after "## ", e.g. "1.2 (2024-03-01)". */
  headingRaw: string;
  version: string | null;
  date: string | null;
  /** True iff `date` matches `YYYY-MM-DD`. */
  dateValid: boolean;
  /** Bullet content, marker (`*` or `-`) and surrounding whitespace stripped. */
  bullets: string[];
  /** Non-blank body lines that are neither blank nor a recognised bullet. */
  strayLines: string[];
}

const ENTRY_HEADING_RE = /^(\S+)\s+\(([^)]*)\)\s*$/;
const HISTORY_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const BULLET_RE = /^[*-]\s+(.*)$/;

/** Parse a HISTORY.md text into its entries, in file order (top first). */
export function parseHistoryEntries(text: string): HistoryEntry[] {
  const lines = text.split(/\r\n|\r|\n/);
  const headingIdxs: number[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (/^##\s+/.test(lines[i] ?? "")) headingIdxs.push(i);
  }

  const entries: HistoryEntry[] = [];
  for (let h = 0; h < headingIdxs.length; h++) {
    const start = headingIdxs[h]!;
    const end = h + 1 < headingIdxs.length ? headingIdxs[h + 1]! : lines.length;
    const headingRaw = (lines[start] ?? "").replace(/^##\s+/, "").trim();
    const m = ENTRY_HEADING_RE.exec(headingRaw);
    const version = m ? (m[1] ?? null) : null;
    const date = m ? (m[2] ?? "").trim() : null;
    const dateValid = date !== null && HISTORY_DATE_RE.test(date);

    const bullets: string[] = [];
    const strayLines: string[] = [];
    for (let i = start + 1; i < end; i++) {
      const line = (lines[i] ?? "").trim();
      if (line === "") continue;
      const bm = BULLET_RE.exec(line);
      if (bm) {
        bullets.push((bm[1] ?? "").trim());
      } else {
        strayLines.push(line);
      }
    }

    entries.push({ headingRaw, version, date, dateValid, bullets, strayLines });
  }
  return entries;
}

/**
 * Compare two version strings by dot-separated segment: numeric segments
 * compare numerically, non-numeric segments compare lexically. Good enough
 * for the `<major>.<minor>[.<patch>]` versions HISTORY.md and `.kmn` files
 * use; not a full semver implementation.
 */
export function compareVersions(a: string, b: string): number {
  const pa = a.split(".");
  const pb = b.split(".");
  const len = Math.max(pa.length, pb.length);
  for (let i = 0; i < len; i++) {
    const sa = pa[i] ?? "0";
    const sb = pb[i] ?? "0";
    const na = Number(sa);
    const nb = Number(sb);
    if (Number.isNaN(na) || Number.isNaN(nb)) {
      if (sa !== sb) return sa < sb ? -1 : 1;
      continue;
    }
    if (na !== nb) return na - nb;
  }
  return 0;
}

// ---------------------------------------------------------------------------
// README.md "Supported Platforms" parsing (5.7)
// ---------------------------------------------------------------------------

const README_PLATFORMS_HEADING = "## Supported Platforms";

/**
 * Parse the platform list `renderReadmeMd` (engine `helpDocsRender.ts`)
 * writes under "## Supported Platforms" — a run of `- <platform>` bullets
 * ending at the next heading or end of file. `[]` when the section is absent.
 */
export function parseReadmePlatforms(readmeMdText: string): string[] {
  const lines = readmeMdText.split(/\r\n|\r|\n/);
  const headingIdx = lines.findIndex((l) => l.trim() === README_PLATFORMS_HEADING);
  if (headingIdx === -1) return [];

  const platforms: string[] = [];
  for (let i = headingIdx + 1; i < lines.length; i++) {
    const line = lines[i] ?? "";
    if (/^##\s+/.test(line.trim())) break;
    const m = /^-\s+(.*)$/.exec(line.trim());
    if (m) platforms.push((m[1] ?? "").trim());
  }
  return platforms;
}

// ---------------------------------------------------------------------------
// $pagename parsing / formatting (11.7)
// ---------------------------------------------------------------------------

/** Reverse `phpSingleQuoteEscape` (engine `escapeHtml.ts`): `\\` then `\'`. */
function phpSingleQuoteUnescape(s: string): string {
  let out = "";
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]!;
    if (ch === "\\" && i + 1 < s.length) {
      const next = s[i + 1]!;
      if (next === "\\" || next === "'") {
        out += next;
        i++;
        continue;
      }
    }
    out += ch;
  }
  return out;
}

/** Parse the `$pagename = '...'` assignment out of a help.php text, or `null` if absent. */
export function parsePagename(phpText: string): string | null {
  const m = /\$pagename\s*=\s*'((?:\\.|[^'\\])*)'/.exec(phpText);
  if (!m) return null;
  return phpSingleQuoteUnescape(m[1] ?? "");
}

/**
 * The expected `$pagename` value for a display name (contracts/help-header.md,
 * criterion 11.7): "<Display Name> Keyboard Help", or "<Display Name> Help"
 * when the display name already ends with the word "Keyboard". Mirrors
 * `packageDocs.ts`'s `helpSitePageName` in the engine package — duplicated
 * here because keyboard-lint cannot import the engine (`lint-not-to-engine`);
 * the help-header contract is the source of truth both converge on.
 */
export function expectedPagename(displayName: string): string {
  const name = displayName.replace(/\s+/g, " ").trim();
  return /\bkeyboard$/i.test(name) ? `${name} Help` : `${name} Keyboard Help`;
}

