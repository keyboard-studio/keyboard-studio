// data-states parsing (11.6)
// ---------------------------------------------------------------------------

const DATA_STATES_RE = /\bdata-states\s*=\s*"([^"]*)"|\bdata-states\s*=\s*'([^']*)'/gi;

/** Every layer id named across all `data-states="..."` attributes, deduped, in document order. */
export function extractDataStatesLayers(html: string): string[] {
  const layers: string[] = [];
  const seen = new Set<string>();
  let m: RegExpExecArray | null;
  DATA_STATES_RE.lastIndex = 0;
  while ((m = DATA_STATES_RE.exec(html)) !== null) {
    const raw = m[1] ?? m[2] ?? "";
    for (const part of raw.split(/[,\s]+/)) {
      const name = part.trim();
      if (name !== "" && !seen.has(name)) {
        seen.add(name);
        layers.push(name);
      }
    }
  }
  return layers;
}

// ---------------------------------------------------------------------------
// Body normalization (11.9) and inline-style extraction (11.10)
// ---------------------------------------------------------------------------

const KEYBOARD_LAYOUT_SECTION_RE = /<h2>Keyboard Layout<\/h2>[\s\S]*?(?=<h2>|<\/body>|$)/i;

/** Strip a leading `<?php ... ?>` header block (the help-site header, spec 076 FR-003). */
export function stripPhpHeader(text: string): string {
  return text.replace(/^\s*<\?php[\s\S]*?\?>\s*/, "");
}

/** Strip the welcome-only "Keyboard Layout" section (spec 076 FR-004) so welcome/help bodies compare fairly. */
export function stripKeyboardLayoutSection(html: string): string {
  return html.replace(KEYBOARD_LAYOUT_SECTION_RE, "");
}

function collapseWhitespace(s: string): string {
  return s.replace(/\s+/g, " ").trim();
}

/**
 * Normalize a welcome/help body for the 11.9 parity comparison: strip the PHP
 * header (help-only) and the "Keyboard Layout" section (welcome-only), then
 * collapse whitespace so formatting differences don't register as content
 * differences (criterion 11.9 wording).
 */
export function normalizeDocBody(html: string): string {
  return collapseWhitespace(stripKeyboardLayoutSection(stripPhpHeader(html)));
}

const STYLE_ATTR_RE = /\bstyle\s*=\s*"([^"]*)"|\bstyle\s*=\s*'([^']*)'/gi;
const STYLE_BLOCK_RE = /<style\b[^>]*>([\s\S]*?)<\/style>/gi;

/**
 * Strip whitespace entirely rather than collapsing it to one space: unlike
 * HTML body text, CSS whitespace never separates otherwise-adjacent tokens
 * (`color:red` and `color: red` render identically), so "modulo non-rendering
 * whitespace" (criterion 11.10) means whitespace-insensitive, not just
 * run-collapsed.
 */
function stripAllWhitespace(s: string): string {
  return s.replace(/\s+/g, "");
}

/**
 * Every inline style declaration in a document, in document order: `style="..."`
 * attribute values followed by `<style>...</style>` block contents, each with
 * whitespace stripped entirely (criterion 11.10: "identical modulo non-rendering
 * whitespace").
 */
export function extractInlineStyles(html: string): string[] {
  const styles: string[] = [];
  let m: RegExpExecArray | null;
  STYLE_ATTR_RE.lastIndex = 0;
  while ((m = STYLE_ATTR_RE.exec(html)) !== null) {
    styles.push(stripAllWhitespace(m[1] ?? m[2] ?? ""));
  }
  STYLE_BLOCK_RE.lastIndex = 0;
  while ((m = STYLE_BLOCK_RE.exec(html)) !== null) {
    styles.push(stripAllWhitespace(m[1] ?? ""));
  }
  return styles;
}

/** Array equality by value (used to compare extracted style lists). */
export function arraysEqual(a: readonly string[], b: readonly string[]): boolean {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

// ---------------------------------------------------------------------------
// Tag-balance scanner (11.5) — the DOMParser deviation, see module header.
// ---------------------------------------------------------------------------

/** HTML void elements: never pushed onto the open-tag stack (no closing tag expected). */
export const VOID_ELEMENTS: ReadonlySet<string> = new Set([
  "area",
  "base",
  "br",
  "col",
  "embed",
  "hr",
  "img",
  "input",
  "link",
  "meta",
  "param",
  "source",
  "track",
  "wbr",
]);

export interface UnbalancedTag {
  tag: string;
  kind: "unclosed" | "mismatched" | "stray-closing";
}

const TAG_RE = /<!--[\s\S]*?-->|<\/([a-zA-Z][a-zA-Z0-9-]*)\s*>|<([a-zA-Z][a-zA-Z0-9-]*)\b([^>]*)>/g;

/**
 * A dependency-free, void-element-aware tag-balance scanner (spec 076
 * research R7 — see module header for why this replaces DOMParser). Finds
 * unclosed elements, elements closed out of nesting order, and stray closing
 * tags with no matching open tag. Comments are skipped; PHP `<?php ... ?>`
 * regions are not special-cased (the header is stripped by callers that need
 * to ignore it).
 */
export function findUnbalancedTags(html: string): UnbalancedTag[] {
  const findings: UnbalancedTag[] = [];
  const stack: string[] = [];
  let m: RegExpExecArray | null;
  TAG_RE.lastIndex = 0;
  while ((m = TAG_RE.exec(html)) !== null) {
    const closingName = m[1];
    const openingName = m[2];
    const attrs = m[3] ?? "";
    if (closingName !== undefined) {
      const name = closingName.toLowerCase();
      const idx = stack.lastIndexOf(name);
      if (idx === -1) {
        findings.push({ tag: name, kind: "stray-closing" });
      } else {
        for (let i = stack.length - 1; i > idx; i--) {
          findings.push({ tag: stack[i]!, kind: "mismatched" });
        }
        stack.length = idx;
      }
    } else if (openingName !== undefined) {
      const name = openingName.toLowerCase();
      const selfClosed = /\/\s*$/.test(attrs);
      if (!VOID_ELEMENTS.has(name) && !selfClosed) {
        stack.push(name);
      }
    }
  }
  for (const tag of stack) {
    findings.push({ tag, kind: "unclosed" });
  }
  return findings;
}
