// Upstream kmc-kmn message tables, loaded lazily.
//
// kmc-kmn reports every compiler message as a `CompilerEvent` whose numeric
// `code` packs severity | namespace | base (developer-utils'
// `CompilerErrorMask`), e.g. ERROR_StoreDoesNotExist = 0x50201D =
// Error(0x500000) | KmnCompiler(0x2000) | 0x01D. There is no `severity` field
// and no symbolic name on the wire. Both are decoded here from upstream's own
// tables — `CompilerError` / `CompilerErrorSeverity` from
// @keymanapp/developer-utils and the `KmnCompilerMessages` /
// `KmwCompilerMessages` constant tables exported by @keymanapp/kmc-kmn — never
// from a local copy of the values.
//
// Both packages are imported DYNAMICALLY, like kmc-kmn in ./index.ts: a static
// import of developer-utils pulls ~340 KB (raw) of its XML/project readers
// into the studio's entry chunk. Everything that needs these tables runs after
// the compiler has loaded anyway (compile() / the validator oracle), so they
// ride the same lazy chunk.

import type { DiagnosticPlatform, LintSeverity } from "@keyboard-studio/contracts";

export interface KmcMessageTables {
  /** Studio severity for a numeric kmc-kmn code. Debug/Verbose/Info → "info". */
  severity(code: number): LintSeverity;
  /**
   * Upstream symbolic name for a numeric kmc-kmn code (e.g.
   * `0x502049` → `"ERROR_InvalidIf"`), or undefined for a code neither
   * message table defines.
   */
  name(code: number): string | undefined;
  /**
   * Compile-target platform for a numeric kmc-kmn code (#2378).
   *
   * - `"web"` — the KmwCompiler namespace (`0x7000`, e.g.
   *   `ERROR_TouchLayoutFileDoesNotExist`, `INFO_MinimumWebEngineVersion`),
   *   plus the web-only KmnCompiler codes in
   *   `WEB_ONLY_KMN_MESSAGE_NAMES` below.
   * - `"desktop"` — every other KmnCompiler-namespace code: the .kmn
   *   rules, which both the desktop and the web pass report.
   * - `undefined` — any other namespace (Ldml, Model, Package, …):
   *   kmc-kmn never emits those; an unexpected one stays unowned so
   *   general panels keep showing it instead of it being silently
   *   assigned to a platform.
   *
   * "Web-only" here means **emitted only by the web pass** (target=1 /
   * `WriteCompiledKeyboard`), proven per code against kmc-kmn 19 — not
   * "the feature only affects web output". The distinction matters: the
   * version-gate codes (`ERROR_90FeatureOnlyEmbedCSS`,
   * `ERROR_90FeatureOnlyLayoutFile`) name web-only features but the
   * shared WASM parser enforces them on BOTH passes, so they stay
   * `"desktop"`. Conversely the codes in the set below fire only when the
   * web pass runs, even though they carry the `0x2000` namespace
   * (upstream's `CompilerErrorNamespace` docs: "some errors generated by
   * kmc-kmn/kmw-compiler are from kmc-kmn namespace for legacy reasons").
   */
  platform(code: number): DiagnosticPlatform | undefined;
}

/**
 * Upstream symbolic names of the KmnCompiler-namespace codes that are
 * emitted ONLY by the web pass (see {@link KmcMessageTables.platform}).
 * Matched against the upstream symbolic name from
 * {@link KmcMessageTables.name}, never against a local copy of the numeric
 * values. Twenty-two codes in kmc-kmn 19, grouped by the evidence:
 *
 * - Touch-layout / KeymanWeb family — the legacy-namespace codes:
 *   `ERROR_140FeatureOnlyContextAndNotAnyWeb` (direct-WASM proven:
 *   target=1 only), `ERROR_InvalidTouchLayoutFile`,
 *   `ERROR_NotSupportedInKeymanWebContext`,
 *   `ERROR_NotSupportedInKeymanWebOutput`,
 *   `ERROR_NotSupportedInKeymanWebStore`,
 *   `ERROR_TouchLayoutInvalidIdentifier`,
 *   `ERROR_VirtualCharacterKeysNotSupportedInKeymanWeb`,
 *   `WARN_ExtendedShiftFlagsNotSupportedInKeymanWeb`,
 *   `WARN_TouchLayoutCustomKeyNotDefined`,
 *   `WARN_TouchLayoutFontShouldBeSameForAllPlatforms`,
 *   `WARN_TouchLayoutMissingLayer`, `WARN_TouchLayoutMissingRequiredKeys`,
 *   `WARN_TouchLayoutSpecialLabelOnNormalKey`,
 *   `WARN_TouchLayoutUnidentifiedKey`.
 * - Embed-JS file (kmw-compiler.js only; the missing-file check runs when
 *   the `.js` is assembled): `WARN_EmbedJsFileMissing`. NOTE:
 *   `ERROR_90FeatureOnlyEmbedCSS` is deliberately NOT here — it fires on
 *   both passes (see the platform doc above).
 * - Web-pass-only JS checks (kmw-compiler/ only; no desktop-pass path):
 *   `ERROR_InvalidBegin` ("required to compile a KeymanWeb keyboard"),
 *   `WARN_HelpFileMissing` (`&KMW_HELPFILE`),
 *   `ERROR_VirtualKeysNotValidForMnemonicLayouts`,
 *   `WARN_DontMixChiralAndNonChiralModifiers` ("for web target"),
 *   `HINT_UnreachableKeyCode` (K_SHIFT / touch keys in JS output),
 *   `ERROR_InvalidKeyCode` (touch-layout dictionary check, only called
 *   from `WriteCompiledKeyboard`), `WARN_OptionStoreNameInvalid`
 *   (JS-identifier character set).
 *
 * DRIFT WARNING: a future web-only code whose name is not in this set
 * silently tags `"desktop"` — it still shows in the desktop pane (never
 * dropped app-wide: the review `DiagnosticsPanel` shows everything), but
 * the desktop pane will show it until the name is added here. Re-check
 * this set on every kmc-kmn upgrade; a new `0x7000` code is safe (the
 * namespace branch catches it). `compile.test.ts` pins all 22 names plus
 * the desktop controls, so an upstream rename fails loudly.
 */
const WEB_ONLY_KMN_MESSAGE_NAMES: ReadonlySet<string> = new Set([
  // Touch-layout / KeymanWeb family (legacy 0x2000 namespace).
  "ERROR_140FeatureOnlyContextAndNotAnyWeb",
  "ERROR_InvalidTouchLayoutFile",
  "ERROR_NotSupportedInKeymanWebContext",
  "ERROR_NotSupportedInKeymanWebOutput",
  "ERROR_NotSupportedInKeymanWebStore",
  "ERROR_TouchLayoutInvalidIdentifier",
  "ERROR_VirtualCharacterKeysNotSupportedInKeymanWeb",
  "WARN_ExtendedShiftFlagsNotSupportedInKeymanWeb",
  "WARN_TouchLayoutCustomKeyNotDefined",
  "WARN_TouchLayoutFontShouldBeSameForAllPlatforms",
  "WARN_TouchLayoutMissingLayer",
  "WARN_TouchLayoutMissingRequiredKeys",
  "WARN_TouchLayoutSpecialLabelOnNormalKey",
  "WARN_TouchLayoutUnidentifiedKey",
  // Embed-JS file (web output assembly only).
  "WARN_EmbedJsFileMissing",
  // Web-pass-only JS checks.
  "ERROR_InvalidBegin",
  "WARN_HelpFileMissing",
  "ERROR_VirtualKeysNotValidForMnemonicLayouts",
  "WARN_DontMixChiralAndNonChiralModifiers",
  "HINT_UnreachableKeyCode",
  "ERROR_InvalidKeyCode",
  "WARN_OptionStoreNameInvalid",
]);

const MESSAGE_NAME = /^(FATAL|ERROR|WARN|HINT|INFO|VERBOSE|DEBUG)_/;

let _tablesPromise: Promise<KmcMessageTables> | null = null;

async function buildTables(): Promise<KmcMessageTables> {
  const [devUtils, kmn] = await Promise.all([
    import("@keymanapp/developer-utils"),
    import("@keymanapp/kmc-kmn"),
  ]);
  const { CompilerError, CompilerErrorNamespace, CompilerErrorSeverity } = devUtils;

  const names = new Map<number, string>();
  // KmwCompilerMessages extends KmnCompilerMessages; getOwnPropertyNames on
  // each class yields only that class's own constants, so walk both.
  for (const table of [kmn.KmnCompilerMessages, kmn.KmwCompilerMessages] as const) {
    for (const key of Object.getOwnPropertyNames(table)) {
      const value = (table as unknown as Record<string, unknown>)[key];
      if (typeof value === "number" && MESSAGE_NAME.test(key) && !names.has(value)) {
        names.set(value, key);
      }
    }
  }

  return {
    severity(code: number): LintSeverity {
      const severity = CompilerError.severity(code);
      if (severity >= CompilerErrorSeverity.Fatal) return "fatal";
      if (severity >= CompilerErrorSeverity.Error) return "error";
      if (severity >= CompilerErrorSeverity.Warn) return "warning";
      if (severity >= CompilerErrorSeverity.Hint) return "hint";
      return "info";
    },
    name(code: number): string | undefined {
      return names.get(code);
    },
    platform(code: number): DiagnosticPlatform | undefined {
      const namespace = CompilerError.namespace(code);
      if (namespace === CompilerErrorNamespace.KmwCompiler) return "web";
      if (namespace !== CompilerErrorNamespace.KmnCompiler) return undefined;
      const name = names.get(code);
      if (name !== undefined && WEB_ONLY_KMN_MESSAGE_NAMES.has(name)) return "web";
      return "desktop";
    },
  };
}

/** Load (once) and return the upstream message tables. */
export function loadKmcMessageTables(): Promise<KmcMessageTables> {
  if (_tablesPromise === null) {
    _tablesPromise = buildTables().catch((err: unknown) => {
      _tablesPromise = null; // allow a later retry
      throw err;
    });
  }
  return _tablesPromise;
}
